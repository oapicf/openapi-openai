#ifndef TINY_CPP_CLIENT_RealtimeResponse_H_
#define TINY_CPP_CLIENT_RealtimeResponse_H_


#include <string>
#include "bourne/json.hpp"
#include "Helpers.h"
#include "Object.h"
#include "RealtimeConversationItem.h"
#include "RealtimeResponse_status_details.h"
#include "RealtimeResponse_usage.h"
#include <list>

namespace Tiny {


/*! \brief The response resource.
 *
 *  \ingroup Models
 *
 */

class RealtimeResponse{
public:

    /*! \brief Constructor.
	 */
    RealtimeResponse();
    RealtimeResponse(std::string jsonString);


    /*! \brief Destructor.
	 */
    virtual ~RealtimeResponse();


    /*! \brief Retrieve a bourne JSON representation of this class.
	 */
    bourne::json toJson();


    /*! \brief Fills in members of this class from bourne JSON object representing it.
	 */
    void fromJson(std::string jsonObj);

	/*! \brief Get The unique ID of the response.
	 */
	std::string getId();

	/*! \brief Set The unique ID of the response.
	 */
	void setId(std::string  id);
	/*! \brief Get The object type, must be `realtime.response`.
	 */
	std::string getObject();

	/*! \brief Set The object type, must be `realtime.response`.
	 */
	void setObject(std::string  object);
	/*! \brief Get The final status of the response (`completed`, `cancelled`, `failed`, or  `incomplete`). 
	 */
	std::string getStatus();

	/*! \brief Set The final status of the response (`completed`, `cancelled`, `failed`, or  `incomplete`). 
	 */
	void setStatus(std::string  status);
	/*! \brief Get 
	 */
	RealtimeResponse_status_details getStatusDetails();

	/*! \brief Set 
	 */
	void setStatusDetails(RealtimeResponse_status_details  status_details);
	/*! \brief Get The list of output items generated by the response.
	 */
	std::list<RealtimeConversationItem> getOutput();

	/*! \brief Set The list of output items generated by the response.
	 */
	void setOutput(std::list <RealtimeConversationItem> output);
	/*! \brief Get Developer-provided string key-value pairs associated with this response. 
	 */
	Object getMetadata();

	/*! \brief Set Developer-provided string key-value pairs associated with this response. 
	 */
	void setMetadata(Object  metadata);
	/*! \brief Get 
	 */
	RealtimeResponse_usage getUsage();

	/*! \brief Set 
	 */
	void setUsage(RealtimeResponse_usage  usage);


    private:
    std::string id{};
    std::string object{};
    std::string status{};
    RealtimeResponse_status_details status_details;
    std::list<RealtimeConversationItem> output;
    Object metadata;
    RealtimeResponse_usage usage;
};
}

#endif /* TINY_CPP_CLIENT_RealtimeResponse_H_ */
