package org.openapitools.server.api.model

import org.openapitools.server.api.model.RealtimeConversationItem
import org.openapitools.server.api.model.RealtimeResponseStatusDetails
import org.openapitools.server.api.model.RealtimeResponseUsage
import com.squareup.moshi.JsonClass

@JsonClass(generateAdapter = true)
data class RealtimeResponse(
    /** The unique ID of the response. */
    val id: kotlin.String? = null,
    /** The object type, must be &#x60;realtime.response&#x60;. */
    val `object`: kotlin.String? = null,
    /** The final status of the response (&#x60;completed&#x60;, &#x60;cancelled&#x60;, &#x60;failed&#x60;, or  &#x60;incomplete&#x60;).  */
    val status: kotlin.String? = null,
    val statusDetails: RealtimeResponseStatusDetails? = null,
    /** The list of output items generated by the response. */
    val output: kotlin.collections.List<RealtimeConversationItem>? = null,
    /** Developer-provided string key-value pairs associated with this response.  */
    val metadata: kotlin.Any? = null,
    val usage: RealtimeResponseUsage? = null
)
