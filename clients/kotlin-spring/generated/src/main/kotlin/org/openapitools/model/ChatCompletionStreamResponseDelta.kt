/**
 * A chat completion delta generated by streamed model responses.
 * @param content The contents of the chunk message.
 * @param functionCall 
 * @param toolCalls 
 * @param role The role of the author of this message.
 * @param refusal The refusal message generated by the model.
 */
data class ChatCompletionStreamResponseDelta(

    @Schema(description = "The contents of the chunk message.")
    @param:JsonProperty("content")
    @get:JsonProperty("content") val content: kotlin.String? = null,

    @field:Valid
    @Schema(description = "")
    @Deprecated(message = "")
    @field:JsonInclude(JsonInclude.Include.NON_NULL)
    @field:JsonSetter(nulls = Nulls.SKIP)
    @param:JsonProperty("function_call")
    @get:JsonProperty("function_call") val functionCall: ChatCompletionStreamResponseDeltaFunctionCall? = null,

    @field:Valid
    @Schema(description = "")
    @field:JsonInclude(JsonInclude.Include.NON_NULL)
    @field:JsonSetter(nulls = Nulls.SKIP)
    @param:JsonProperty("tool_calls")
    @get:JsonProperty("tool_calls") val toolCalls: kotlin.collections.List<ChatCompletionMessageToolCallChunk>? = null,

    @Schema(description = "The role of the author of this message.")
    @field:JsonInclude(JsonInclude.Include.NON_NULL)
    @field:JsonSetter(nulls = Nulls.SKIP)
    @param:JsonProperty("role")
    @get:JsonProperty("role") val role: ChatCompletionStreamResponseDelta.Role? = null,

    @Schema(description = "The refusal message generated by the model.")
    @param:JsonProperty("refusal")
    @get:JsonProperty("refusal") val refusal: kotlin.String? = null
) {

    /**
    * The role of the author of this message.
    * Values: system,user,assistant,tool
    */
    enum class Role(@get:JsonValue val value: kotlin.String) {

        system("system"),
        user("user"),
        assistant("assistant"),
        tool("tool");

        companion object {
            @JvmStatic
            @JsonCreator
            fun forValue(value: kotlin.String): Role {
                return values().firstOrNull{it -> it.value == value}
                    ?: throw IllegalArgumentException("Unexpected value '$value' for enum 'Role'")
            }
        }
    }

}

