import { RealtimeResponseStatusDetails } from './realtime-response-status-details';
import { RealtimeResponseUsage } from './realtime-response-usage';
import { RealtimeConversationItem } from './realtime-conversation-item';


/**
 * The response resource.
 */
export interface RealtimeResponse { 
  /**
   * The unique ID of the response.
   */
  id?: string;
  /**
   * The object type, must be `realtime.response`.
   */
  object?: RealtimeResponse.ObjectEnum;
  /**
   * The final status of the response (`completed`, `cancelled`, `failed`, or  `incomplete`). 
   */
  status?: RealtimeResponse.StatusEnum;
  status_details?: RealtimeResponseStatusDetails;
  /**
   * The list of output items generated by the response.
   */
  output?: Array<RealtimeConversationItem>;
  /**
   * Developer-provided string key-value pairs associated with this response. 
   */
  metadata?: object | null;
  usage?: RealtimeResponseUsage;
}
export namespace RealtimeResponse {
  export const ObjectEnum = {
    RealtimeResponse: 'realtime.response'
  } as const;
  export type ObjectEnum = typeof ObjectEnum[keyof typeof ObjectEnum];
  export const StatusEnum = {
    Completed: 'completed',
    Cancelled: 'cancelled',
    Failed: 'failed',
    Incomplete: 'incomplete'
  } as const;
  export type StatusEnum = typeof StatusEnum[keyof typeof StatusEnum];
}


